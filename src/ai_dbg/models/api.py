@final
class ServerInfoResponse(BaseModel):
    """根路由响应：服务自描述信息

    有了这个 response_model，OpenAPI 才能生成具体字段，前端无需再手写收窄层。
    """

    service: str
    base_url: str
    # 静态资源 URL 前缀（不含主机名），客户端据此拼接图片地址，避免硬编码服务端目录映射
    assets_url_prefix: str
    description: str
    status: str
    timestamp: datetime
    version: str
    routes: List[ApiRouteInfo]


