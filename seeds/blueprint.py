"""种子世界数据：构建开发/测试用的初始蓝图。

本模块只做数据构建：战役设定、全局规则、世界、舞台与角色。玩法相关的数据（战斗、
遭遇与推进规则）在 SRPG 规则落地后再按新数据结构补充。
"""

